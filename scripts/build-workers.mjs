import {build} from 'esbuild';
import {mkdir,writeFile,copyFile,readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
await mkdir('public',{recursive:true});
await mkdir('public/licenses',{recursive:true});
await copyFile('vendor/cubejs/LICENSE','public/licenses/cubejs.txt');
const visionHash=createHash('sha256');
for(const file of ['public/vision.worker.js','modules/cube-vision/cpp/Detector.cpp','public/vision/cube-vision.js','public/vision/cube-vision.wasm']){
  try{visionHash.update(await readFile(file));}catch(error){if(!file.startsWith('public/vision/'))throw error;}
}
await writeFile('src/camera/visionVersion.ts',`// Generated by build:workers; versions the worker and its WASM assets together.\nexport const VISION_VERSION = '${visionHash.digest('hex').slice(0,16)}';\n`);
await build({entryPoints:['src/solver/worker.ts'],bundle:true,platform:'browser',format:'iife',target:'es2020',outfile:'public/solver.worker.js',minify:true,legalComments:'inline'});
const solverVersion=createHash('sha256').update(await readFile('public/solver.worker.js')).digest('hex').slice(0,16);
await writeFile('src/solver/workerVersion.ts',`// Generated by build:workers; keeps the app and background protocol together.\nexport const SOLVER_VERSION = '${solverVersion}';\n`);
const runtime=await build({entryPoints:['src/solver/runtime.ts'],bundle:true,platform:'browser',format:'iife',target:'es2020',write:false,minify:true,legalComments:'inline'});
await writeFile('src/solver/generated.ts',`// Generated from the vendored MIT-licensed cubejs runtime. Run npm run build:workers.\nexport const SOLVER_RUNTIME = ${JSON.stringify(runtime.outputFiles[0].text)};\n`);
console.log('Built browser worker and native background solver bundle.');
